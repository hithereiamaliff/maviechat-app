// Builds the code editor page (scripts/code-editor/editor.js on CodeMirror 6, MIT) into one HTML
// string the app loads in a web view, offline: apps/mobile/src/features/code/editorPage.generated.ts.
// It also lists the packages bundled into it (scripts/code-editor/packages.json), whose licence
// notices the About screen carries (scripts/check-licenses.mjs). Run `npm run code-editor`.
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { build } from 'esbuild';

const root = path.resolve(import.meta.dirname, '..');
const result = await build({
  entryPoints: [path.join(root, 'scripts/code-editor/editor.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['safari15', 'chrome100'],
  write: false,
  metafile: true,
  legalComments: 'none',
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const page = `<!doctype html>
<html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no">
<style>html,body{margin:0;padding:0;height:100%;overflow:hidden;-webkit-text-size-adjust:100%}#editor{height:100%}</style>
</head><body><div id="editor"></div><script>${script}</script></body></html>`;

const packages = [
  ...new Set(
    Object.keys(result.metafile.inputs)
      .filter((input) => input.includes('node_modules/'))
      .map((input) => {
        const parts = input.split('node_modules/').pop().split('/');
        return parts[0].startsWith('@') ? `${parts[0]}/${parts[1]}` : parts[0];
      }),
  ),
].sort();

const target = path.join(root, 'apps/mobile/src/features/code/editorPage.generated.ts');
writeFileSync(
  target,
  `// Generated by scripts/gen-code-editor.mjs (CodeMirror 6, MIT; notices in About). Run \`npm run code-editor\`.\nexport const EDITOR_PAGE = ${JSON.stringify(page)};\n`,
);
writeFileSync(path.join(root, 'scripts/code-editor/packages.json'), `${JSON.stringify(packages, null, 2)}\n`);
console.log(`✓ code editor page (${Math.round(page.length / 1024)} KB, ${packages.length} packages) → ${path.relative(root, target)}`);
