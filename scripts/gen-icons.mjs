// Generates apps/mobile/src/components/icons.generated.ts from the Heroicons package
// (24px outline set, MIT). Add a name to ICONS and run `npm run icons`.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'node_modules/heroicons/24/outline');
const target = path.join(root, 'apps/mobile/src/components/icons.generated.ts');

const ICONS = [
  'adjustments-horizontal',
  'archive-box',
  'archive-box-arrow-down',
  'arrow-down',
  'arrow-path',
  'arrow-right-start-on-rectangle',
  'arrow-up',
  'bars-3',
  'bars-arrow-down',
  'bars-arrow-up',
  'bookmark',
  'bookmark-slash',
  'camera',
  'chat-bubble-bottom-center-text',
  'chat-bubble-left',
  'check',
  'chevron-down',
  'chevron-left',
  'chevron-right',
  'chevron-up',
  'clipboard-document',
  'cog-6-tooth',
  'command-line',
  'document-text',
  'ellipsis-horizontal',
  'exclamation-triangle',
  'eye-slash',
  'folder',
  'folder-open',
  'globe-alt',
  'information-circle',
  'light-bulb',
  'link',
  'magnifying-glass',
  'microphone',
  'paper-clip',
  'pencil',
  'pencil-square',
  'photo',
  'puzzle-piece',
  'plus',
  'signal',
  'sparkles',
  'squares-2x2',
  'stop-circle',
  'trash',
  'user-circle',
  'wrench-screwdriver',
  'x-mark',
];

const entries = ICONS.map((name) => {
  const svg = readFileSync(path.join(source, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path\b[^>]*\bd="([^"]+)"/g)].map((match) => match[1]);
  if (paths.length === 0) throw new Error(`no paths in ${name}.svg`);
  return `  '${name}': ${JSON.stringify(paths)},`;
});

const licence = readFileSync(path.join(root, 'node_modules/heroicons/LICENSE'), 'utf8').split('\n')[2]?.trim();
writeFileSync(
  target,
  [
    '// Generated by scripts/gen-icons.mjs from Heroicons (https://heroicons.com, MIT licence).',
    `// ${licence ?? 'Copyright (c) Tailwind Labs, Inc.'}`,
    '// Do not edit by hand.',
    '',
    '/** Outline icons, 24×24, drawn with a 1.5 stroke. */',
    'export const ICON_PATHS = {',
    ...entries,
    '} as const;',
    '',
    'export type IconName = keyof typeof ICON_PATHS;',
    '',
  ].join('\n'),
);
console.log(`✓ ${ICONS.length} icons → ${path.relative(root, target)}`);
