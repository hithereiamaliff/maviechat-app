// Generates apps/mobile/src/lib/emoji.generated.ts from the emoji-datasource package
// (iamcal/emoji-data, MIT): each emoji's code points, short names and group, in the order its
// pickers show them. Open WebUI keys emoji by the same code points and short names, so a status
// set on the phone shows on the web. Run `npm run emoji` after updating the package.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const source = path.join(root, 'node_modules/emoji-datasource');
const target = path.join(root, 'apps/mobile/src/lib/emoji.generated.ts');

const version = JSON.parse(readFileSync(path.join(source, 'package.json'), 'utf8')).version;
const emoji = JSON.parse(readFileSync(path.join(source, 'emoji.json'), 'utf8')).sort((a, b) => a.sort_order - b.sort_order);

// Skin tones and hair styles are parts of other emoji, not ones to pick on their own.
const groups = [];
for (const item of emoji) if (item.category !== 'Component' && !groups.includes(item.category)) groups.push(item.category);

const lines = emoji.map((item) => {
  for (const name of item.short_names) if (!/^[a-z0-9_+-]+$/.test(name)) throw new Error(`unexpected short name: ${name}`);
  return `${item.unified} ${item.short_names.join(',')} ${groups.indexOf(item.category)}`;
});

writeFileSync(
  target,
  [
    `// Generated by scripts/gen-emoji.mjs from emoji-datasource ${version} (https://github.com/iamcal/emoji-data, MIT licence).`,
    '// Do not edit by hand.',
    '',
    '/** The emoji picker\'s groups, in order. */',
    `export const EMOJI_GROUPS = ${JSON.stringify(groups)} as const;`,
    '',
    '/**',
    ' * One emoji a line, in the pickers\' order: its code points (hex, joined by "-"), its short names',
    ' * (comma-separated; the first is the one Open WebUI saves) and its group (an index into',
    ' * EMOJI_GROUPS; -1 for skin tones and other parts).',
    ' */',
    `export const EMOJI_LINES = ${JSON.stringify(lines.join('\n'))};`,
    '',
  ].join('\n'),
);
console.log(`✓ ${lines.length} emoji in ${groups.length} groups → ${path.relative(root, target)}`);
